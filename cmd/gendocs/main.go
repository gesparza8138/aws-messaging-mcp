func main() {
	check := flag.Bool("check", false, "verify pages match instead of writing")
	dir := flag.String("dir", "docs/tools", "output directory")
	flag.Parse()
	if err := run(*check, *dir); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool, dir string) error {
	ctx := context.Background()
	server := mcpserver.NewServer(mcpserver.Deps{Settings: settings.Settings{}, SES: stubSES{}, EUM: stubEUM{}, Files: stubFiles{}})
	clientTransport, serverTransport := mcp.NewInMemoryTransports()
	serverSession, err := server.Connect(ctx, serverTransport, nil)
	if err != nil {
		return err
	}
	defer func() { _ = serverSession.Close() }()
	client := mcp.NewClient(&mcp.Implementation{Name: "gendocs", Version: "0"}, nil)
	session, err := client.Connect(ctx, clientTransport, nil)
	if err != nil {
		return err
	}
	defer func() { _ = session.Close() }()

	tools, err := session.ListTools(ctx, nil)
	if err != nil {
		return err
	}
	pages := map[string][]byte{filepath.Join(dir, "README.md"): index(tools.Tools)}
	for _, tool := range tools.Tools {
		page, err := render(tool)
		if err != nil {
			return fmt.Errorf("%s: %w", tool.Name, err)
		}
		pages[filepath.Join(dir, tool.Name+".md")] = page
	}

	var stale []string
	for path, want := range pages {
		if check {
			got, err := os.ReadFile(path) // #nosec G304 -- paths are built from tool names, not user input
			if err != nil || !bytes.Equal(got, want) {
				stale = append(stale, path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			return err
		}
		if err := os.WriteFile(path, want, 0o600); err != nil {
			return err
		}
	}
	if len(stale) > 0 {
		sort.Strings(stale)
		return fmt.Errorf("stale tool docs (run `go run ./cmd/gendocs`): %v", stale)
	}
	return nil
}

func index(tools []*mcp.Tool) []byte {
	var b bytes.Buffer
	b.WriteString("<!-- generated by cmd/gendocs; do not edit -->\n\n# Tool reference\n\n")
	b.WriteString("| Tool | Description |\n| --- | --- |\n")
	for _, tool := range tools {
		fmt.Fprintf(&b, "| [`%s`](%s.md) | %s |\n", tool.Name, tool.Name, tool.Description)
	}
	return b.Bytes()
}

func render(tool *mcp.Tool) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "<!-- generated by cmd/gendocs; do not edit -->\n\n# `%s`\n\n%s\n", tool.Name, tool.Description)
	if err := schemaBlock(&b, "Input schema", tool.InputSchema); err != nil {
		return nil, err
	}
	if err := schemaBlock(&b, "Output schema", tool.OutputSchema); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

func schemaBlock(b *bytes.Buffer, title string, schema any) error {
	if schema == nil {
		return nil
	}
	raw, err := json.MarshalIndent(schema, "", "  ")
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "\n## %s\n\n```json\n%s\n```\n", title, raw)
	return nil
}
