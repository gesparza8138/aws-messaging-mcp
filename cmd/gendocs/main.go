// Command gendocs renders docs/tools/<name>.md from the live tool registry —
// the same schemas the server advertises over MCP — so the reference pages
// cannot drift from the code. `gendocs -check` (the docs CI job) exits
// non-zero when a page on disk differs from what it would generate.
package main

